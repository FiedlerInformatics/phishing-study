CREATE TABLE PARTICIPANT (
    Participant_ID PRIMARY KEY INT NOT NULL,
    Start_time DATETIME NOT NULL
)

CREATE TABLE ANSWER (
    Survey_ID INT FOREIGN KEY NOT NULL,
    Question_ID INT FOREIGN KEY NOT NULL,
    OfferedAnswer_ID INT FOREIGN KEY NOT NULL,
    Participant_ID INT FOREIGN KEY NOT NULL
)

CREATE TABLE Survey (
    Survey_ID PRIMARY KEY INT NOT NULL,
    Survey_name TEXT NOT NULL
)

CREATE TABLE QUESTION (
    Question_ID FOREIGN KEY INT NOT NULL,
    Question_text TEXT NOT NULL
)

CREATE TABLE SURVEY_QUESTION (
    Survey_ID FOREIGN KEY INT NOT NULL,
    Question_ID FOREIGN KEY INT NOT NULL
)

CREATE TABLE SURVEY_QUESTION_ANSWER (
    Survey_ID INT FOREIGN KEY NOT NULL,
    Question_ID INT FOREIGN KEY NOT NULL,
    OfferedAnswer_ID INT FOREIGN KEY NOT NULL
)

CREATE TABLE OFFERED_ANSWER (
    OfferedAnwer_ID INT PRIMARY KEY,
    AnwerText TEXT NOT NULL
)

CREATE TABLE DEMOGRAPHICS_SURVEY (
    Survey_ID INT NOT NULL,
    Question_ID INT NOT NULL
)

